#ifndef TASK_INIT_H
#define TASK_INIT_H

/*
*********************************************************************************************************
*   业务任务创建结果
*   任务模块只报告资源创建状态，由调用者决定失败处理；本接口不依赖启动模块。
*   创建接口只在系统启动时调用一次，调用者保证此阶段不被业务任务抢占。
*********************************************************************************************************
*/
typedef enum
{
    TASK_CREATE_OK = 0,       /* 命令队列和任务均创建成功 */
    TASK_CREATE_ERR_QUEUE,    /* 命令队列创建失败，未创建任务 */
    TASK_CREATE_ERR_TASK      /* 任务创建失败，已释放本次创建的队列 */
} Task_CreateResult_t;

#endif /* TASK_INIT_H */
